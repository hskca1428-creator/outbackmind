def get_high_priority_gear():
    """Return all High-priority catalog items."""
    return [item for item in GEAR_CATALOG if item.get("priority", "").lower() == "high"]


def find_gear_matches(text, limit=5):
    """Simple keyword matcher for safe recommendations."""
    text = (text or "").lower()
    matches = []

    for item in GEAR_CATALOG:
        score = 0
        for keyword in item.get("keywords", []):
            if keyword and keyword.lower() in text:
                score += 1

        if score:
            priority_boost = 3 if item.get("priority") == "High" else 1 if item.get("priority") == "Medium" else 0
            matches.append((score + priority_boost, item))

    matches.sort(key=lambda x: x[0], reverse=True)

    seen = set()
    results = []
    for _, item in matches:
        if item["name"] not in seen:
            seen.add(item["name"])
            results.append(item)
        if len(results) >= limit:
            break

    return results
