@app.get("/trip-plans/{plan_id}/pdf")
def download_trip_plan_pdf(plan_id: int):
    db = SessionLocal()
    try:
        row = db.query(TripPlan).filter(TripPlan.id == plan_id).first()
        if not row:
            raise HTTPException(status_code=404, detail="Trip plan not found")

        pdf_path = build_trip_plan_pdf(row.id, row.request, row.plan)

        return FileResponse(
            pdf_path,
            media_type="application/pdf",
            filename=f"outbackmind_trip_plan_{row.id}.pdf",
        )
    finally:
        db.close()
@app.post("/plan-trip")
def plan_trip(payload: TripPlanRequest):
    db = SessionLocal()
    try:
        plan_text = generate_trip_plan(payload.request)

        entry = TripPlan(
            request=payload.request,
            plan=plan_text,
        )
        db.add(entry)
        db.commit()
        db.refresh(entry)

        return {
            "id": entry.id,
            "request": entry.request,
            "plan": entry.plan,
            "created_at": entry.created_at.isoformat(),
        }
    except Exception as e:
        db.rollback()
        raise HTTPException(status_code=500, detail=str(e))
    finally:
        db.close()


