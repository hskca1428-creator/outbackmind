client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))

class Question(BaseModel):
    question: str
    mode: str = "normal"


@app.post("/ask")
def ask(question: Question):
    try:
        prompt = question.question

        if question.mode == "emergency":
            prompt = f"Emergency situation:\n{prompt}\nProvide immediate, practical steps."

        response = client.responses.create(
            model="gpt-4.1-mini",
            input=prompt
        )

        answer_text = response.output[0].content[0].text

        # save to DB
        db = SessionLocal()
        try:
            new_entry = QuestionLog(
                question=question.question,
                answer=answer_text,
                mode=question.mode
            )
            db.add(new_entry)
            db.commit()
        finally:
            db.close()

        return {
            "answer": answer_text,
            "recommended_gear": []
        }

    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
